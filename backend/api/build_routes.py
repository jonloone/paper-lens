"""
Build Flow API Routes
Phase 1 Week 7-8: Backend API Implementation

Endpoints for the 6-step data product creation workflow:
1. POST /api/v1/build/start - Start workflow and validate product definition
2. GET  /api/v1/build/sources - Fetch available sources from DataHub
3. POST /api/v1/build/validate-sql - Validate SQL using Trino
4. POST /api/v1/build/preview - Execute SQL preview with LIMIT
5. POST /api/v1/build/generate-artifacts - Generate ODCS, dbt, Airflow files
6. POST /api/v1/build/deploy - Create Git branch, commit, and PR
"""

from fastapi import APIRouter, HTTPException, Body
from pydantic import BaseModel, Field
from typing import List, Optional, Dict, Any
import uuid
from datetime import datetime
import logging

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/api/v1/build", tags=["build"])


# ============================================================================
# Request/Response Models
# ============================================================================

class ProductDefinition(BaseModel):
    """Step 1: Product definition"""
    name: str = Field(..., pattern="^[a-z_]+$", description="Product name (lowercase, underscores only)")
    displayName: str
    description: str
    domain: str
    owner: str
    tags: List[str] = Field(default_factory=list)
    schedule: Dict[str, Any]
    sla: Dict[str, Any]


class StartWorkflowRequest(BaseModel):
    definition: ProductDefinition


class StartWorkflowResponse(BaseModel):
    workflow_id: str
    contract_draft: str
    status: str = "created"


class Source(BaseModel):
    """Step 2: Source metadata"""
    id: str  # DataHub URN
    name: str
    schema_name: str = Field(alias="schema")
    database: str
    qualityScore: float
    rowCount: int
    columns: List[Dict[str, Any]]
    lastUpdated: str
    description: Optional[str] = None

    class Config:
        populate_by_name = True


class SourcesResponse(BaseModel):
    sources: List[Source]
    total: int


class ValidateSQLRequest(BaseModel):
    """Step 3: SQL validation"""
    sql: str
    sources: List[str]  # DataHub URNs


class ValidateSQLResponse(BaseModel):
    valid: bool
    plan: Optional[str] = None
    estimatedRows: Optional[int] = None
    errors: Optional[List[str]] = None
    warnings: Optional[List[str]] = None


class PreviewRequest(BaseModel):
    """Step 3: SQL preview"""
    sql: str
    limit: int = 100


class PreviewResponse(BaseModel):
    columns: List[str]
    rows: List[List[Any]]
    executionTimeMs: int
    rowCount: int


class GenerateArtifactsRequest(BaseModel):
    """Step 6: Artifact generation"""
    workflow_id: str


class Artifact(BaseModel):
    path: str
    content: str


class GenerateArtifactsResponse(BaseModel):
    artifacts: Dict[str, Artifact]


class DeployRequest(BaseModel):
    """Step 6: Deployment"""
    workflow_id: str


class DeployResponse(BaseModel):
    branch: str
    commit_sha: str
    pr_url: str


